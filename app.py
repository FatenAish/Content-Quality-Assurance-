def technical_checks(article_title, source_url, soup, findings):
    statuses = []

    # Meta robots
    robots = soup.find("meta", attrs={"name": re.compile("^robots$", re.I)})
    robots_value = (robots.get("content", "") if robots else "").lower()

    status = "REVIEW" if "noindex" in robots_value else "PASS"
    add_finding(
        findings, article_title, source_url,
        "Meta Robots",
        status,
        "Checks whether the article is marked noindex.",
        robots_value,
        "SEO / Backend"
    )
    statuses.append(status)

    # Canonical
    canonical_tag = soup.find(
        "link",
        attrs={"rel": lambda v: v and "canonical" in [
            x.lower() for x in (v if isinstance(v, list) else [v])
        ]}
    )

    canonical = normalize_url(
        canonical_tag.get("href", "")
    ) if canonical_tag else ""

    if not canonical:
        status = "REVIEW"
        why = "Canonical tag is missing."
    elif comparable_url(canonical) != comparable_url(source_url):
        status = "REVIEW"
        why = "Canonical points to a genuinely different URL."
    else:
        status = "PASS"
        why = "Canonical matches the source URL."

    add_finding(
        findings, article_title, source_url,
        "Canonical",
        status,
        why,
        canonical,
        "SEO / Backend"
    )
    statuses.append(status)

    # H1
    h1s = [clean_text(x.get_text(" ")) for x in soup.find_all("h1")]

    status = "PASS" if len(h1s) == 1 else "REVIEW"
    add_finding(
        findings, article_title, source_url,
        "H1",
        status,
        "Checks for missing or multiple H1 elements.",
        f"Count={len(h1s)} | " + " || ".join(h1s[:5]),
        "Content / SEO"
    )
    statuses.append(status)

    # Hidden content
    hidden_hits = find_hidden_content(soup)
    status = "REVIEW" if hidden_hits else "PASS"

    add_finding(
        findings, article_title, source_url,
        "Hidden Text / Hidden Links",
        status,
        "Static HTML contains hidden text or links. Some hidden UI is legitimate, so manual review is required.",
        " | ".join(hidden_hits[:10]),
        "Backend / SEO"
    )
    statuses.append(status)

    return statuses, canonical, robots_value, h1s

