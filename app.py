def extract_editorial_fields(body):
    """Extract content fields that visible_text() misses: headings, image ALT and captions."""
    headings = []
    image_alts = []
    image_captions = []

    if body is None:
        return {"headings": headings, "image_alts": image_alts, "image_captions": image_captions}

    for h in body.find_all(re.compile(r"^h[1-6]$")):
        value = clean_text(h.get_text(" "))
        if value:
            headings.append(f"{h.name.upper()}: {value}")

    for img in body.find_all("img"):
        alt = clean_text(img.get("alt", ""))
        if alt:
            image_alts.append(alt)

    for cap in body.find_all("figcaption"):
        value = clean_text(cap.get_text(" "))
        if value:
            image_captions.append(value)

    # WordPress/common caption classes that may not use <figcaption>.
    for node in body.select(".wp-caption-text, .caption, .image-caption, [class*='caption']"):
        value = clean_text(node.get_text(" "))
        if value and value not in image_captions:
            image_captions.append(value)

    return {
        "headings": list(dict.fromkeys(headings))[:120],
        "image_alts": list(dict.fromkeys(image_alts))[:200],
        "image_captions": list(dict.fromkeys(image_captions))[:200],
    }


def _collect_http_urls(obj):
    """Collect actual URLs returned by the Responses API/web-search payload."""
    urls = []
    if isinstance(obj, dict):
        for key, value in obj.items():
            if key == "url" and isinstance(value, str) and value.startswith(("http://", "https://")):
                urls.append(value)
            else:
                urls.extend(_collect_http_urls(value))
    elif isinstance(obj, list):
        for value in obj:
            urls.extend(_collect_http_urls(value))
    return list(dict.fromkeys(urls))


def _response_output_text(payload):
    """Extract assistant output_text from a raw Responses API JSON response."""
    for item in payload.get("output", []) or []:
        if not isinstance(item, dict) or item.get("type") != "message":
            continue
        for content in item.get("content", []) or []:
            if isinstance(content, dict) and content.get("type") == "output_text":
                return content.get("text", "") or ""
    return ""


def _host_without_www(url):
    host = get_host(url)
    return host[4:] if host.startswith("www.") else host


def _is_blocked_verification_source(url):
    host = _host_without_www(url)
    if not host:
        return True
    return any(host == d or host.endswith("." + d) for d in AI_BLOCKED_SOURCE_DOMAINS)


def _reconcile_with_web_source(candidate_url, web_urls):
    """
    Never trust a model-written source URL blindly.
    Keep it only when the Responses web-search payload actually consulted that URL/domain.
    If the exact URL is absent but the same official domain was consulted, return the real
    consulted URL from the API payload instead of a potentially invented path.
    """
    candidate_url = clean_text(candidate_url)
    if not candidate_url or _is_blocked_verification_source(candidate_url):
        return ""

    candidate_cmp = comparable_url(candidate_url)
    for url in web_urls:
        if comparable_url(url) == candidate_cmp and not _is_blocked_verification_source(url):
            return url

    candidate_host = _host_without_www(candidate_url)
    same_host = [
        url for url in web_urls
        if _host_without_www(url) == candidate_host
        and not _is_blocked_verification_source(url)
    ]
    return same_host[0] if same_host else ""


