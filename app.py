def content_checks(article_title, source_url, text, findings):
    statuses = []
    low = text.lower()
    words = tokenize(text)
    word_count = len(words)

    # Thin content
    if word_count < THIN_CONTENT_FAIL:
        status = "FAIL"
    elif word_count < THIN_CONTENT_REVIEW:
        status = "REVIEW"
    else:
        status = "PASS"

    add_finding(
        findings, article_title, source_url,
        "Thin Content",
        status,
        "Checks whether the visible article content is unusually short.",
        f"Word Count = {word_count}",
        "Content"
    )
    statuses.append(status)

    # Blocked words
    blocked_hits = []
    for phrase in BLOCKED_WORDS:
        count = low.count(phrase.lower())
        if count:
            blocked_hits.append(f"{phrase} ({count})")

    status = "FAIL" if blocked_hits else "PASS"
    add_finding(
        findings, article_title, source_url,
        "Internal Blocked Words",
        status,
        "Matches MyBayut's own internal prohibited-word list. This is not a Google banned-word list.",
        ", ".join(blocked_hits[:30]),
        "Content / Editor"
    )
    statuses.append(status)

    # Risky phrases
    risky_hits = []
    risky_evidence = []

    for phrase in RISKY_PHRASES:
        count = low.count(phrase.lower())
        if count:
            contexts = phrase_contexts(text, phrase, max_contexts=2)
            risky_hits.append({
                "phrase": phrase,
                "count": count,
                "contexts": contexts,
            })

            if contexts:
                risky_evidence.append(
                    f"Matched phrase: {phrase!r} | Count: {count} | "
                    f"Context: " + " || ".join(contexts)
                )
            else:
                risky_evidence.append(
                    f"Matched phrase: {phrase!r} | Count: {count}"
                )

    # This rule is intentionally disabled because Google does not publish
    # an official risky-phrases or banned-words list.

    # Suspicious / unexpected terms
    suspicious_hits = []
    suspicious_evidence = []

    for phrase in INJECTION_RISK_TERMS:
        count = low.count(phrase.lower())
        if count:
            contexts = phrase_contexts(text, phrase, max_contexts=3)
            suspicious_hits.append((phrase, count))
            suspicious_evidence.append(
                f"Term: {phrase!r} | Count: {count} | Context: "
                + (" || ".join(contexts) if contexts else "Context unavailable")
            )

    status = "REVIEW" if suspicious_hits else "PASS"

    add_finding(
        findings,
        article_title,
        source_url,
        "Suspicious / Unexpected Terms",
        status,
        (
            "One or more terms unusual for normal MyBayut editorial content were detected. "
            "Review the context for possible hacked/injected, inappropriate, or off-topic content. "
            "A detected term is not automatically a Google spam violation."
            if suspicious_hits else
            "No configured suspicious/unexpected terms were detected."
        ),
        " | ".join(suspicious_evidence[:30]),
        "Content / Backend"
    )
    statuses.append(status)

    # Keyword repetition
    stopwords = ARABIC_STOPWORDS | ENGLISH_STOPWORDS
    counts = Counter(
        w for w in words
        if len(w) >= 4
        and not w.isdigit()
        and w not in stopwords
    )

    candidates = []
    for w, n in counts.most_common(40):
        density = (n / max(word_count, 1)) * 100
        if n >= KEYWORD_REPEAT_REVIEW and density >= 2.0:
            candidates.append((w, n, density))

    max_density = max((d for _, _, d in candidates), default=0)
    max_repeat = max((n for _, n, _ in candidates), default=0)

    # Requires both unusually high frequency AND meaningful density.
    if max_repeat >= KEYWORD_REPEAT_FAIL and max_density >= 3.5:
        status = "FAIL"
    elif candidates:
        status = "REVIEW"
    else:
        status = "PASS"

    add_finding(
        findings, article_title, source_url,
        "Keyword Repetition",
        status,
        "Checks unusually concentrated non-stopword terms. Raw repetition alone is not treated as spam.",
        ", ".join(f"{w}={n} ({d:.1f}%)" for w, n, d in candidates[:15]),
        "Content / SEO"
    )
    statuses.append(status)

    # Repeated 5-word phrases, excluding common page boilerplate.
    grams = Counter(
        " ".join(words[i:i+5])
        for i in range(max(0, len(words) - 4))
    )
    boilerplate_fragments = (
        "دقائق للقراءة", "تم التحديث", "minutes read", "last updated"
    )
    repeated_phrases = [
        (p, n) for p, n in grams.most_common(30)
        if n >= PHRASE_REPEAT_REVIEW
        and not any(b in p for b in boilerplate_fragments)
    ]

    max_phrase_repeat = repeated_phrases[0][1] if repeated_phrases else 0

    if max_phrase_repeat >= PHRASE_REPEAT_FAIL:
        status = "FAIL"
    elif max_phrase_repeat >= PHRASE_REPEAT_REVIEW:
        status = "REVIEW"
    else:
        status = "PASS"

    add_finding(
        findings, article_title, source_url,
        "Repeated Phrases",
        status,
        "Checks for heavily repeated five-word phrases after excluding common page boilerplate.",
        " | ".join(f"{p!r}={n}" for p, n in repeated_phrases[:10]),
        "Content / SEO"
    )
    statuses.append(status)

    return statuses, word_count

