def build_sitewide_analysis(links_df, total_articles):
    findings = []

    if links_df.empty:
        return pd.DataFrame(), pd.DataFrame(), pd.DataFrame()

    internal_df = links_df[links_df["Internal"] == True].copy()

    target_summary = (
        internal_df
        .groupby("Target URL")
        .agg(
            Articles_Linking=("Source URL", "nunique"),
            Total_Links=("Target URL", "size"),
            Unique_Anchors=("Anchor Text", "nunique")
        )
        .reset_index()
    )

    target_summary["Article Share"] = (
        target_summary["Articles_Linking"]
        / max(total_articles, 1)
    )

    target_summary = target_summary.sort_values(
        ["Articles_Linking", "Total_Links"],
        ascending=False
    )

    for _, row in target_summary.iterrows():
        share = float(row["Article Share"])

        if share >= SITE_TARGET_SHARE_FAIL:
            status = "FAIL"
        elif share >= SITE_TARGET_SHARE_REVIEW:
            status = "REVIEW"
        else:
            continue

        findings.append({
            "Rule": "Site-wide Target Concentration",
            "Status": status,
            "Why": "The same internal target is linked from an unusually large share of audited articles.",
            "Evidence": (
                f"{row['Target URL']} | "
                f"Articles={int(row['Articles_Linking'])} | "
                f"Share={share:.1%} | "
                f"Total Links={int(row['Total_Links'])}"
            ),
            "Responsible": "SEO"
        })

    internal_df["Anchor Normalized"] = (
        internal_df["Anchor Text"]
        .fillna("")
        .str.strip()
        .str.lower()
    )

    usable = internal_df[
        internal_df["Anchor Normalized"] != ""
    ].copy()

    anchor_target = (
        usable
        .groupby(["Anchor Normalized", "Target URL"])
        .size()
        .reset_index(name="Count")
    )

    anchor_totals = (
        usable
        .groupby("Anchor Normalized")
        .size()
        .reset_index(name="Anchor Total")
    )

    anchor_target = anchor_target.merge(
        anchor_totals,
        on="Anchor Normalized",
        how="left"
    )

    anchor_target["Target Share"] = (
        anchor_target["Count"]
        / anchor_target["Anchor Total"]
    )

    anchor_target = anchor_target.sort_values(
        "Count",
        ascending=False
    )

    for _, row in anchor_target.iterrows():
        if int(row["Anchor Total"]) < 20:
            continue

        share = float(row["Target Share"])
        count = int(row["Count"])

        if share >= SITE_ANCHOR_TARGET_SHARE_FAIL and count >= 100:
            status = "FAIL"
        elif share >= SITE_ANCHOR_TARGET_SHARE_REVIEW and count >= 50:
            status = "REVIEW"
        else:
            continue

        findings.append({
            "Rule": "Site-wide Exact Anchor Concentration",
            "Status": status,
            "Why": "The same anchor text points overwhelmingly to the same destination across many articles.",
            "Evidence": (
                f"Anchor={row['Anchor Normalized']!r} | "
                f"Target={row['Target URL']} | "
                f"Count={count} | "
                f"Share={share:.1%}"
            ),
            "Responsible": "SEO / Content"
        })

    return (
        target_summary,
        anchor_target,
        pd.DataFrame(findings)
    )

