def clean_text(value):
    return re.sub(r"\s+", " ", str(value or "")).strip()

def normalize_url(url):
    url = clean_text(url)
    if not url:
        return ""
    return urldefrag(url)[0]


def comparable_url(url):
    """Normalize URL for equality checks without treating percent-encoding as a different URL."""
    url = normalize_url(url)
    if not url:
        return ""
    try:
        p = urlparse(url)
        scheme = (p.scheme or "https").lower()
        host = p.netloc.lower()
        if host == "bayut.com":
            host = "www.bayut.com"
        path = unicodedata.normalize("NFC", unquote(p.path or "/"))
        path = re.sub(r"/+", "/", path)
        if path != "/" and path.endswith("/"):
            path = path[:-1]
        return f"{scheme}://{host}{path}"
    except Exception:
        return unicodedata.normalize("NFC", unquote(url)).rstrip("/")

def ignored_url(url):
    low = (url or "").lower()
    return any(p in low for p in IGNORED_URL_PATTERNS)

def get_host(url):
    try:
        return urlparse(url).netloc.lower().split(":")[0]
    except Exception:
        return ""

def is_internal(url):
    host = get_host(url)
    return (
        host == SITE_DOMAIN
        or host == f"www.{SITE_DOMAIN}"
        or host.endswith(f".{SITE_DOMAIN}")
    )

