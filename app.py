def run_audit(input_file, output_file, limit=None, ai_content=None):
    if ai_content is None:
        ai_content = AI_CONTENT_QA_DEFAULT

    if ai_content and not OPENAI_API_KEY:
        raise RuntimeError(
            "Official-source Content QA is enabled but OPENAI_API_KEY is not set. "
            "Set OPENAI_API_KEY, or explicitly use --no-ai-content for the legacy non-research checks."
        )

    print(f"Reading: {input_file}")
    print(f"Official-source AI Content QA: {'ON' if ai_content else 'OFF'}")

    df = pd.read_excel(input_file)

    if URL_COLUMN not in df.columns:
        raise ValueError(
            f"Column '{URL_COLUMN}' not found. Available columns: {list(df.columns)}"
        )

    if TITLE_COLUMN not in df.columns:
        df[TITLE_COLUMN] = ""

    work = df[[TITLE_COLUMN, URL_COLUMN]].copy()
    work[URL_COLUMN] = work[URL_COLUMN].astype(str).str.strip()

    work = work[
        work[URL_COLUMN].str.match(r"^https?://", na=False)
    ].copy()

    work[URL_COLUMN] = work[URL_COLUMN].map(normalize_url)

    work = work[
        work[URL_COLUMN].map(is_internal)
        & work[URL_COLUMN].map(is_mybayut_article)
    ].copy()

    work = work.drop_duplicates(subset=[URL_COLUMN])

    if limit:
        work = work.head(limit)

    total = len(work)
    print(f"Unique MyBayut articles to audit: {total:,}")

    s = build_session()

    article_rows = []
    finding_rows = []
    link_rows = []

    target_cache = {}

    for i, row in enumerate(work.itertuples(index=False), start=1):
        article_title = clean_text(getattr(row, "_0"))
        source_url = clean_text(getattr(row, "_1"))

        print(f"[{i:,}/{total:,}] {source_url}")

        result = fetch(s, source_url)

        if not result["ok"]:
            add_finding(
                finding_rows,
                article_title,
                source_url,
                "Article Fetch",
                "REVIEW",
                "Could not fetch the article.",
                result["error"],
                "Backend / SEO"
            )

            article_rows.append({
                "Title/Topic": article_title,
                "Source URL": source_url,
                "HTTP Status": None,
                "Final URL": "",
                "Redirect Count": 0,
                "Word Count": 0,
                "Body Links": 0,
                "Internal Links": 0,
                "External Links": 0,
                "Overall Status": "REVIEW",
                "Reasons": "Article Fetch",
            })
            continue

        r = result["response"]

        if r.status_code in (404, 410):
            add_finding(
                finding_rows,
                article_title,
                source_url,
                "Article Fetch",
                "FAIL",
                f"Source article returns HTTP {r.status_code}.",
                "",
                "Backend / SEO"
            )

            article_rows.append({
                "Title/Topic": article_title,
                "Source URL": source_url,
                "HTTP Status": r.status_code,
                "Final URL": r.url,
                "Redirect Count": len(r.history),
                "Word Count": 0,
                "Body Links": 0,
                "Internal Links": 0,
                "External Links": 0,
                "Overall Status": "FAIL",
                "Reasons": "Article Fetch",
            })
            continue

        content_type = r.headers.get("content-type", "").lower()
        if "text/html" not in content_type:
            add_finding(
                finding_rows,
                article_title,
                source_url,
                "Article Fetch",
                "REVIEW",
                "The URL did not return normal HTML.",
                content_type,
                "Backend / SEO"
            )
            continue

        soup = BeautifulSoup(r.text, "html.parser")
        body = find_article_body(soup)
        text = visible_text(body)

        page_statuses = []

        content_statuses, word_count = content_checks(
            article_title,
            source_url,
            text,
            finding_rows
        )
        page_statuses.extend(content_statuses)

        entity_statuses = entity_accuracy_checks(
            article_title,
            source_url,
            text,
            finding_rows
        )
        page_statuses.extend(entity_statuses)

        if ai_content:
            try:
                ai_statuses = ai_content_qa_checks(
                    article_title,
                    source_url,
                    text,
                    body,
                    finding_rows
                )
                page_statuses.extend(ai_statuses)
            except Exception as e:
                # Operational failure is visible and explicit; never fabricate a factual QA result.
                add_finding(
                    finding_rows, article_title, source_url,
                    "Content QA: System Error",
                    "REVIEW",
                    "Official-source Content QA could not complete for this article. No factual verdict was fabricated.",
                    f"{type(e).__name__}: {e}",
                    "Content / Backend"
                )
                page_statuses.append("REVIEW")

        technical_statuses, canonical, robots_value, h1s = technical_checks(
            article_title,
            source_url,
            soup,
            finding_rows
        )
        page_statuses.extend(technical_statuses)

        links = extract_links(body, source_url)

        link_statuses = page_link_checks(
            article_title,
            source_url,
            links,
            word_count,
            finding_rows
        )
        page_statuses.extend(link_statuses)

        # Check every unique target only once, then reuse result
        page_checked_links = []

        for link in links:
            target = link["Target URL"]

            if target not in target_cache:
                target_result = fetch(s, target)

                if target_result["ok"]:
                    tr = target_result["response"]
                    target_cache[target] = {
                        "Target HTTP Status": tr.status_code,
                        "Target Final URL": tr.url,
                        "Target Redirect Count": len(tr.history),
                        "Target Redirect Chain": target_result["redirect_chain"],
                        "Target Error": "",
                    }
                else:
                    target_cache[target] = {
                        "Target HTTP Status": None,
                        "Target Final URL": "",
                        "Target Redirect Count": 0,
                        "Target Redirect Chain": "",
                        "Target Error": target_result["error"],
                    }

            link.update(target_cache[target])

            status_code = link["Target HTTP Status"]
            redirect_count = link["Target Redirect Count"]

            if status_code in (404, 410):
                link["Link Status"] = "FAIL"
                link["Link Reason"] = f"Broken link: HTTP {status_code}"
            elif status_code is None:
                link["Link Status"] = "REVIEW"
                link["Link Reason"] = "Target could not be verified."
            elif status_code >= 500:
                link["Link Status"] = "REVIEW"
                link["Link Reason"] = f"Server error HTTP {status_code}"
            elif link["Internal"] and redirect_count > 0:
                link["Link Status"] = "REVIEW"
                link["Link Reason"] = "Internal URL redirects; update link to final URL."
            else:
                link["Link Status"] = "PASS"
                link["Link Reason"] = "Target resolved successfully."

            link["Title/Topic"] = article_title
            page_checked_links.append(link)
            link_rows.append(link)

        broken = [
            x for x in page_checked_links
            if x["Link Status"] == "FAIL"
        ]

        status = "FAIL" if broken else "PASS"

        add_finding(
            finding_rows,
            article_title,
            source_url,
            "Broken Links",
            status,
            "Checks article-body links returning 404 or 410.",
            " | ".join(
                f"{x['Anchor Text']!r} -> {x['Target URL']} ({x['Target HTTP Status']})"
                for x in broken[:10]
            ),
            "Content / SEO"
        )

        page_statuses.append(status)

        internal_redirects = [
            x for x in page_checked_links
            if x["Internal"] and x["Target Redirect Count"] > 0
        ]

        status = "REVIEW" if internal_redirects else "PASS"

        add_finding(
            finding_rows,
            article_title,
            source_url,
            "Internal Redirect Links",
            status,
            "Checks internal article links that still point to redirecting URLs.",
            " | ".join(
                f"{x['Target URL']} -> {x['Target Final URL']}"
                for x in internal_redirects[:10]
            ),
            "SEO / Content"
        )

        page_statuses.append(status)

        # Overall FAIL is reserved for stronger technical/editorial failures.
        source_findings = [
            f for f in finding_rows
            if f["Source URL"] == source_url
        ]
        critical_fail_rules = {
            "Article Fetch",
            "Broken Links",
            "Internal Blocked Words",
        }
        has_critical_fail = any(
            f["Status"] == "FAIL" and f["Rule"] in critical_fail_rules
            for f in source_findings
        )
        has_any_review_or_fail = any(
            f["Status"] in {"REVIEW", "FAIL"}
            for f in source_findings
        )

        if has_critical_fail:
            overall_status = "FAIL"
        elif has_any_review_or_fail:
            overall_status = "REVIEW"
        else:
            overall_status = "PASS"

        article_findings = [
            f["Rule"]
            for f in finding_rows
            if f["Source URL"] == source_url
            and f["Status"] != "PASS"
        ]

        article_rows.append({
            "Title/Topic": article_title,
            "Source URL": source_url,
            "HTTP Status": r.status_code,
            "Final URL": r.url,
            "Redirect Count": len(r.history),
            "Redirect Chain": result["redirect_chain"],
            "Word Count": word_count,
            "Body Links": len(links),
            "Internal Links": sum(1 for x in links if x["Internal"]),
            "External Links": sum(1 for x in links if not x["Internal"]),
            "Canonical": canonical,
            "Robots": robots_value,
            "H1 Count": len(h1s),
            "Overall Status": overall_status,
            "Reasons": " | ".join(article_findings),
        })

        if i % SAVE_EVERY == 0:
            print(f"Saving checkpoint at article {i:,} ...")
            save_checkpoint(
                article_rows,
                finding_rows,
                link_rows
            )

        if SLEEP_BETWEEN_ARTICLES:
            time.sleep(SLEEP_BETWEEN_ARTICLES)

    issues_df = build_issues_only(
        article_rows,
        finding_rows,
        link_rows
    )

    print(f"Writing issues-only Excel: {output_file}")
    print(f"Actionable issue rows: {len(issues_df):,}")

    with pd.ExcelWriter(output_file, engine="openpyxl") as writer:
        issues_df.to_excel(
            writer,
            sheet_name="Issues Only",
            index=False
        )

