def page_link_checks(article_title, source_url, links, word_count, findings):
    statuses = []

    total_links = len(links)
    internal_links = sum(1 for x in links if x["Internal"])
    external_links = total_links - internal_links

    density = total_links / max(word_count, 1) * 1000

    if density >= LINK_DENSITY_FAIL:
        status = "FAIL"
    elif density >= LINK_DENSITY_REVIEW:
        status = "REVIEW"
    else:
        status = "PASS"

    add_finding(
        findings, article_title, source_url,
        "Link Density",
        status,
        "Checks whether article-body link volume is unusually high compared with content length.",
        f"Total={total_links}; Internal={internal_links}; External={external_links}; Links/1000 words={density:.1f}",
        "SEO / Content"
    )
    statuses.append(status)

    # Generic anchors
    generic = [
        x for x in links
        if x["Anchor Text"].strip().lower() in GENERIC_ANCHORS
    ]

    status = "REVIEW" if generic else "PASS"
    add_finding(
        findings, article_title, source_url,
        "Generic Anchor Text",
        status,
        "Checks for vague anchor text such as 'click here' or 'اضغط هنا'.",
        " | ".join(
            f"{x['Anchor Text']} -> {x['Target URL']}"
            for x in generic[:10]
        ),
        "Content / SEO"
    )
    statuses.append(status)

    # Empty anchors
    empty = [x for x in links if not x["Anchor Text"].strip()]

    status = "REVIEW" if empty else "PASS"
    add_finding(
        findings, article_title, source_url,
        "Empty Anchor Text",
        status,
        "Text links with no visible or accessible anchor label were detected.",
        f"Count={len(empty)}",
        "Content / SEO"
    )
    statuses.append(status)

    # Repeated targets
    target_counts = Counter(x["Target URL"] for x in links)
    top_target = target_counts.most_common(1)[0] if target_counts else ("", 0)

    if top_target[1] >= SAME_TARGET_FAIL:
        status = "FAIL"
    elif top_target[1] >= SAME_TARGET_REVIEW:
        status = "REVIEW"
    else:
        status = "PASS"

    add_finding(
        findings, article_title, source_url,
        "Repeated Target in Same Article",
        status,
        "Checks whether the same destination URL is linked excessively within one article.",
        f"{top_target[0]} => {top_target[1]} links" if top_target[1] else "",
        "SEO / Content"
    )
    statuses.append(status)

    # Repeated anchors
    anchor_counts = Counter(
        x["Anchor Text"].lower()
        for x in links
        if x["Anchor Text"]
    )
    top_anchor = anchor_counts.most_common(1)[0] if anchor_counts else ("", 0)

    if top_anchor[1] >= SAME_ANCHOR_FAIL:
        status = "FAIL"
    elif top_anchor[1] >= SAME_ANCHOR_REVIEW:
        status = "REVIEW"
    else:
        status = "PASS"

    add_finding(
        findings, article_title, source_url,
        "Repeated Anchor in Same Article",
        status,
        "Checks whether the same anchor text is repeated excessively within one article.",
        f"{top_anchor[0]!r} => {top_anchor[1]} uses" if top_anchor[1] else "",
        "SEO / Content"
    )
    statuses.append(status)

    return statuses

