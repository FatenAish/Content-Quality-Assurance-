def build_issues_only(article_rows, finding_rows, link_rows):
    """
    One row per actionable issue.
    PASS rows are excluded.
    Link issues contain the exact problematic URL and redirect/broken-link details.
    """
    articles_df = pd.DataFrame(article_rows)
    findings_df = pd.DataFrame(finding_rows)
    links_df = pd.DataFrame(link_rows)

    issue_rows = []

    article_lookup = {}
    if not articles_df.empty and "Source URL" in articles_df.columns:
        article_lookup = {
            r["Source URL"]: r
            for _, r in articles_df.iterrows()
        }

    # Non-link findings.
    # Broken/redirect findings are represented below from link_rows so that
    # the exact wrong URL, anchor, final URL and HTTP details are visible.
    link_aggregate_rules = {
        "Broken Links",
        "Internal Redirect Links",
    }

    if not findings_df.empty:
        bad_findings = findings_df[
            (findings_df["Status"] != "PASS")
            & (~findings_df["Rule"].isin(link_aggregate_rules))
        ].copy()

        for _, f in bad_findings.iterrows():
            article = article_lookup.get(f["Source URL"], {})
            issue_rows.append({
                "Title/Topic": f.get("Title/Topic", ""),
                "Article URL": f.get("Source URL", ""),
                "Article HTTP Status": article.get("HTTP Status", ""),
                "Article Overall Status": article.get("Overall Status", ""),
                "Issue Status": f.get("Status", ""),
                "Issue Type": f.get("Rule", ""),
                "Issue Details": f.get("Why", ""),
                "Problem Link": "",
                "Anchor Text": "",
                "Link Type": "",
                "Link HTTP Status": "",
                "Final Destination": "",
                "Redirect Count": "",
                "Redirect Chain": "",
                "Link Rel": "",
                "Evidence": f.get("Evidence", ""),
                "Responsible": f.get("Responsible", ""),
            })

    # Exact problematic links: one row per wrong link.
    if not links_df.empty:
        bad_links = links_df[links_df["Link Status"] != "PASS"].copy()

        for _, l in bad_links.iterrows():
            article = article_lookup.get(l["Source URL"], {})
            code = l.get("Target HTTP Status", "")
            redirects = l.get("Target Redirect Count", 0)

            if code in (404, 410):
                issue_type = "Broken Link"
                issue_status = "FAIL"
                details = f"The link returns HTTP {code}."
            elif code is None or pd.isna(code):
                issue_type = "Unverified Link"
                issue_status = "REVIEW"
                details = "The target URL could not be verified."
            elif isinstance(code, (int, float)) and code >= 500:
                issue_type = "Target Server Error"
                issue_status = "REVIEW"
                details = f"The target returned HTTP {int(code)}."
            elif bool(l.get("Internal", False)) and redirects and redirects > 0:
                issue_type = "Internal Redirect Link"
                issue_status = "REVIEW"
                details = (
                    "The internal link points to an old/redirecting URL. "
                    "Update the article link to the final destination."
                )
            else:
                issue_type = "Link Issue"
                issue_status = l.get("Link Status", "REVIEW")
                details = l.get("Link Reason", "")

            issue_rows.append({
                "Title/Topic": l.get("Title/Topic", ""),
                "Article URL": l.get("Source URL", ""),
                "Article HTTP Status": article.get("HTTP Status", ""),
                "Article Overall Status": article.get("Overall Status", ""),
                "Issue Status": issue_status,
                "Issue Type": issue_type,
                "Issue Details": details,
                "Problem Link": l.get("Target URL", ""),
                "Anchor Text": l.get("Anchor Text", ""),
                "Link Type": "Internal" if bool(l.get("Internal", False)) else "External",
                "Link HTTP Status": l.get("Target HTTP Status", ""),
                "Final Destination": l.get("Target Final URL", ""),
                "Redirect Count": l.get("Target Redirect Count", ""),
                "Redirect Chain": l.get("Target Redirect Chain", ""),
                "Link Rel": l.get("Rel", ""),
                "Evidence": l.get("Link Reason", ""),
                "Responsible": "SEO / Content" if bool(l.get("Internal", False)) else "Content / SEO",
            })

    issues_df = pd.DataFrame(issue_rows)

    if issues_df.empty:
        return pd.DataFrame(columns=[
            "Title/Topic", "Article URL", "Article HTTP Status",
            "Article Overall Status", "Issue Status", "Issue Type",
            "Issue Details", "Problem Link", "Anchor Text", "Link Type",
            "Link HTTP Status", "Final Destination", "Redirect Count",
            "Redirect Chain", "Link Rel", "Evidence", "Responsible"
        ])

    # Sort the most important items first.
    priority = {"FAIL": 0, "REVIEW": 1}
    issues_df["_priority"] = issues_df["Issue Status"].map(priority).fillna(9)
    issues_df = issues_df.sort_values(
        ["_priority", "Title/Topic", "Issue Type", "Problem Link"],
        ascending=[True, True, True, True]
    ).drop(columns=["_priority"])

    return issues_df.reset_index(drop=True)


