def tokenize(text):
    return re.findall(r"[A-Za-z0-9\u0600-\u06FF]+", (text or "").lower())


def phrase_contexts(text, phrase, max_contexts=3, window=120):
    """
    Return short readable contexts around a matched phrase.
    Prefer sentence-like boundaries; fallback to a character window.
    """
    contexts = []
    low = text.lower()
    phrase_low = phrase.lower()
    start = 0

    while len(contexts) < max_contexts:
        idx = low.find(phrase_low, start)
        if idx == -1:
            break

        left = max(
            low.rfind(".", 0, idx),
            low.rfind("!", 0, idx),
            low.rfind("?", 0, idx),
            low.rfind("؟", 0, idx),
            low.rfind("،", max(0, idx - 180), idx),
        )
        right_candidates = [
            x for x in [
                low.find(".", idx + len(phrase_low)),
                low.find("!", idx + len(phrase_low)),
                low.find("?", idx + len(phrase_low)),
                low.find("؟", idx + len(phrase_low)),
            ] if x != -1
        ]

        if left == -1:
            left = max(0, idx - window)
        else:
            left += 1

        if right_candidates:
            right = min(right_candidates) + 1
            if right - left > 350:
                right = min(len(text), idx + len(phrase) + window)
        else:
            right = min(len(text), idx + len(phrase) + window)

        context = clean_text(text[left:right])
        if context and context not in contexts:
            contexts.append(context)

        start = idx + len(phrase_low)

    return contexts

def worst_status(statuses):
    rank = {"PASS": 0, "REVIEW": 1, "FAIL": 2}
    if not statuses:
        return "PASS"
    return max(statuses, key=lambda s: rank.get(s, 0))

